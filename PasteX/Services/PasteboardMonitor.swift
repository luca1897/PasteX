import AppKit
import Foundation
import ImageIO
import UniformTypeIdentifiers

@MainActor
final class PasteboardMonitor {
    static let shared = PasteboardMonitor()

    var onCapture: ((ClipboardCapture) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var lastCapturedHash: String?
    private var selfCopyHashes: [String: Date] = [:]
    private var includeImages = true
    private var includeFiles = false
    private var ignoreSensitiveContent = true

    private let ignoredTypeNames: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.apple.is-remote-clipboard"
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }

        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.inspectPasteboardIfNeeded()
            }
        }

        RunLoop.main.add(timer!, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func synchronizeCurrentChangeCount() {
        lastChangeCount = pasteboard.changeCount
    }

    func updateConfiguration(_ preferences: CapturePreferences) {
        includeImages = preferences.includeImages
        includeFiles = preferences.includeFiles
        ignoreSensitiveContent = preferences.ignoreSensitiveContent
    }

    func markSelfCopy(type: ClipboardItemType, content: String, payloadData: Data?) {
        let hash = ContentHasher.hash(type: type, content: content, payloadData: payloadData)
        selfCopyHashes[hash] = Date().addingTimeInterval(5)
        synchronizeCurrentChangeCount()
    }

    private func inspectPasteboardIfNeeded() {
        pruneExpiredSelfCopyHashes()

        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }

        lastChangeCount = currentChangeCount

        guard let capture = makeCapture(from: pasteboard, changeCount: currentChangeCount) else { return }
        guard !consumeSelfCopyIfNeeded(capture.contentHash) else { return }
        guard capture.contentHash != lastCapturedHash else { return }

        lastCapturedHash = capture.contentHash
        onCapture?(capture)
    }

    private func makeCapture(from pasteboard: NSPasteboard, changeCount: Int) -> ClipboardCapture? {
        guard !containsIgnoredType(in: pasteboard) else { return nil }

        if containsFileURL(in: pasteboard) {
            guard includeFiles else { return nil }
            return makeFileCapture(from: pasteboard, changeCount: changeCount)
        }

        if let string = pasteboard.string(forType: .string) {
            return makeTextCapture(from: string, changeCount: changeCount)
        }

        guard includeImages else { return nil }

        if let imageCapture = makeImageCapture(from: pasteboard, changeCount: changeCount) {
            return imageCapture
        }

        return nil
    }

    private func makeTextCapture(from rawString: String, changeCount: Int) -> ClipboardCapture? {
        let trimmed = rawString.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        guard trimmed.utf8.count <= 1_000_000 else { return nil }
        guard !ignoreSensitiveContent || !containsSensitiveContent(trimmed) else { return nil }

        let type = classify(trimmed)
        let source = sourceApplicationInfo()
        let preview = trimmed.collapsingWhitespace().truncated(to: 160)

        return ClipboardCapture(
            type: type,
            title: title(for: trimmed, type: type),
            subtitle: subtitle(for: trimmed, type: type),
            preview: preview,
            content: rawString,
            payloadData: nil,
            sourceApp: source.name,
            createdAt: Date(),
            metadata: ClipboardCaptureMetadata(
                bundleIdentifier: source.bundleIdentifier,
                pasteboardChangeCount: changeCount,
                mimeType: mimeType(for: type),
                language: language(for: trimmed, type: type)
            )
        )
    }

    private func makeImageCapture(from pasteboard: NSPasteboard, changeCount: Int) -> ClipboardCapture? {
        let payloadType: NSPasteboard.PasteboardType
        if pasteboard.types?.contains(.png) == true {
            payloadType = .png
        } else if pasteboard.types?.contains(.tiff) == true {
            payloadType = .tiff
        } else {
            return nil
        }

        let payload = pasteboard.data(forType: payloadType)
        guard let payload else { return nil }
        guard payload.count <= 12_000_000 else { return nil }

        let formatter = ByteCountFormatter()
        formatter.countStyle = .file
        let source = sourceApplicationInfo()
        let dimensions = imageDimensions(from: payload)

        return ClipboardCapture(
            type: .image,
            title: "Image from clipboard",
            subtitle: formatter.string(fromByteCount: Int64(payload.count)),
            preview: "Image captured from the macOS clipboard",
            content: "Image from clipboard",
            payloadData: payload,
            sourceApp: source.name,
            createdAt: Date(),
            metadata: ClipboardCaptureMetadata(
                bundleIdentifier: source.bundleIdentifier,
                pasteboardChangeCount: changeCount,
                mimeType: payloadType == .png ? "image/png" : "image/tiff",
                imagePixelWidth: dimensions?.width,
                imagePixelHeight: dimensions?.height,
                byteSize: payload.count,
                sizeLabel: formatter.string(fromByteCount: Int64(payload.count)),
                primaryName: "Clipboard image"
            )
        )
    }

    private func makeFileCapture(from pasteboard: NSPasteboard, changeCount: Int) -> ClipboardCapture? {
        let urls = fileURLs(from: pasteboard)
        guard !urls.isEmpty else { return nil }

        let source = sourceApplicationInfo()
        let fileNames = urls.map(\.lastPathComponent).filter { !$0.isEmpty }
        let title = fileNames.first ?? "File from clipboard"
        let preview = urls.count == 1 ? title : "\(urls.count) files copied"
        let content = urls.map(\.path).joined(separator: "\n")
        let byteSize = totalByteSize(for: urls)
        let formatter = ByteCountFormatter()
        formatter.countStyle = .file
        let sizeLabel = byteSize.map { formatter.string(fromByteCount: Int64($0)) }

        return ClipboardCapture(
            type: .file,
            title: title,
            subtitle: urls.count == 1 ? sizeLabel : "\(urls.count) files",
            preview: preview,
            content: content,
            payloadData: nil,
            sourceApp: source.name,
            createdAt: Date(),
            metadata: ClipboardCaptureMetadata(
                bundleIdentifier: source.bundleIdentifier,
                pasteboardChangeCount: changeCount,
                mimeType: mimeType(for: urls.first),
                byteSize: byteSize,
                sizeLabel: sizeLabel,
                primaryName: title,
                fileCount: urls.count,
                fileNames: Array(fileNames.prefix(12))
            )
        )
    }

    private func containsIgnoredType(in pasteboard: NSPasteboard) -> Bool {
        pasteboard.types?.contains { ignoredTypeNames.contains($0.rawValue) } ?? false
    }

    private func containsFileURL(in pasteboard: NSPasteboard) -> Bool {
        pasteboard.types?.contains(.fileURL) == true
    }

    private func consumeSelfCopyIfNeeded(_ hash: String) -> Bool {
        guard selfCopyHashes.removeValue(forKey: hash) != nil else { return false }
        lastCapturedHash = hash
        return true
    }

    private func pruneExpiredSelfCopyHashes() {
        let now = Date()
        selfCopyHashes = selfCopyHashes.filter { $0.value > now }
    }

    private func containsSensitiveContent(_ text: String) -> Bool {
        if looksLikeCreditCardNumber(text) {
            return true
        }

        let patterns = [
            #"(?i)\b(password|passwd|pwd|secret|api[_-]?key|access[_-]?token|refresh[_-]?token|private[_-]?key)\b\s*[:=]"#,
            #"(?i)\bbearer\s+[a-z0-9._~+/=-]{20,}"#,
            #"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"#,
            #"\b(?:sk|pk|rk|ghp|github_pat)_[A-Za-z0-9_]{20,}\b"#,
            #"(?i)\botp\b\s*[:=]?\s*\d{4,8}\b"#
        ]

        return patterns.contains { pattern in
            text.range(of: pattern, options: .regularExpression) != nil
        }
    }

    private func looksLikeCreditCardNumber(_ text: String) -> Bool {
        let digits = text.filter(\.isNumber)
        guard (13...19).contains(digits.count) else { return false }

        var sum = 0
        var shouldDouble = false

        for character in digits.reversed() {
            guard var digit = Int(String(character)) else { return false }

            if shouldDouble {
                digit *= 2
                if digit > 9 {
                    digit -= 9
                }
            }

            sum += digit
            shouldDouble.toggle()
        }

        return sum % 10 == 0
    }

    private func classify(_ text: String) -> ClipboardItemType {
        if SmartClipboardDetector.primaryColorCandidate(in: text) != nil {
            return .color
        }

        if isWebURL(text) {
            return .url
        }

        if isJSON(text) {
            return .json
        }

        if looksLikeCode(text) {
            return .code
        }

        if looksLikeEmail(text) {
            return .email
        }

        return .text
    }

    private func title(for text: String, type: ClipboardItemType) -> String {
        switch type {
        case .url:
            return text.truncated(to: 90)
        case .json:
            return text.collapsingWhitespace().truncated(to: 90)
        case .code:
            return text.split(whereSeparator: \.isNewline).first.map(String.init)?.truncated(to: 90) ?? "Code snippet"
        case .email:
            return text.split(whereSeparator: \.isNewline).first.map(String.init)?.truncated(to: 90) ?? "Email template"
        case .color:
            return SmartClipboardDetector.primaryColorCandidate(in: text)?.hexRGB ?? "Color"
        case .image:
            return "Image from clipboard"
        case .text:
            return text.split(whereSeparator: \.isNewline).first.map(String.init)?.truncated(to: 90) ?? text.truncated(to: 90)
        case .file:
            return "File"
        }
    }

    private func subtitle(for text: String, type: ClipboardItemType) -> String? {
        switch type {
        case .url:
            return URL(string: text)?.host
        case .json:
            return "JSON document"
        case .code:
            return "Code snippet"
        case .email:
            return "Email or template"
        case .color:
            guard let color = SmartClipboardDetector.primaryColorCandidate(in: text) else { return "Color value" }
            return color.alpha < 1 ? color.rgbaString : color.rgbString
        case .text:
            return "\(text.count) characters"
        case .image:
            return nil
        case .file:
            return "File"
        }
    }

    private func isWebURL(_ text: String) -> Bool {
        guard
            let url = URL(string: text),
            let scheme = url.scheme?.lowercased(),
            ["http", "https"].contains(scheme),
            url.host != nil
        else {
            return false
        }

        return text.rangeOfCharacter(from: .whitespacesAndNewlines) == nil
    }

    private func isJSON(_ text: String) -> Bool {
        guard let data = text.data(using: .utf8) else { return false }
        return (try? JSONSerialization.jsonObject(with: data)) != nil
    }

    private func looksLikeCode(_ text: String) -> Bool {
        let markers = [
            "func ", "function ", "let ", "var ", "const ", "import ", "class ",
            "struct ", "enum ", "SELECT ", "FROM ", "WHERE ", "</", "{", "=>"
        ]

        let uppercase = text.uppercased()

        return markers.contains { marker in
            marker == marker.uppercased() ? uppercase.contains(marker) : text.contains(marker)
        }
    }

    private func looksLikeEmail(_ text: String) -> Bool {
        text.localizedCaseInsensitiveContains("subject:")
            || text.localizedCaseInsensitiveContains("best,")
            || text.localizedCaseInsensitiveContains("regards,")
            || text.localizedCaseInsensitiveContains("hi ")
    }

    private func sourceApplicationInfo() -> (name: String, bundleIdentifier: String?) {
        let app = NSWorkspace.shared.frontmostApplication
        return (app?.localizedName ?? "Unknown App", app?.bundleIdentifier)
    }

    private func mimeType(for type: ClipboardItemType) -> String? {
        switch type {
        case .text, .email:
            return "text/plain"
        case .url:
            return "text/uri-list"
        case .code:
            return "text/plain"
        case .json:
            return "application/json"
        case .color:
            return "text/plain"
        case .image:
            return "image/png"
        case .file:
            return nil
        }
    }

    private func language(for text: String, type: ClipboardItemType) -> String? {
        guard type == .code || type == .json else { return nil }
        if type == .json { return "json" }

        let lowercased = text.lowercased()
        if lowercased.contains("import swiftui") || lowercased.contains("func ") || lowercased.contains("struct ") {
            return "swift"
        }

        if lowercased.contains("function ") || lowercased.contains("const ") || lowercased.contains("=>") {
            return "javascript"
        }

        if lowercased.contains("select ") && lowercased.contains(" from ") {
            return "sql"
        }

        if lowercased.contains("<html") || lowercased.contains("</") {
            return "html"
        }

        return nil
    }

    private func imageDimensions(from data: Data) -> (width: Int, height: Int)? {
        guard
            let source = CGImageSourceCreateWithData(data as CFData, nil),
            let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
            let width = properties[kCGImagePropertyPixelWidth] as? Int,
            let height = properties[kCGImagePropertyPixelHeight] as? Int
        else {
            return nil
        }

        return (width, height)
    }

    private func fileURLs(from pasteboard: NSPasteboard) -> [URL] {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            return urls
        }

        if let nsURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [NSURL] {
            return nsURLs.compactMap { $0 as URL }
        }

        guard let string = pasteboard.string(forType: .fileURL), let url = URL(string: string) else {
            return []
        }

        return [url]
    }

    private func totalByteSize(for urls: [URL]) -> Int? {
        let values = urls.compactMap { url -> Int? in
            guard let resourceValues = try? url.resourceValues(forKeys: [.fileSizeKey]) else { return nil }
            return resourceValues.fileSize
        }

        guard !values.isEmpty else { return nil }
        return values.reduce(0, +)
    }

    private func mimeType(for url: URL?) -> String? {
        guard let extensionValue = url?.pathExtension, !extensionValue.isEmpty else { return nil }
        return UTType(filenameExtension: extensionValue)?.preferredMIMEType
    }
}

private extension String {
    func truncated(to maxLength: Int) -> String {
        guard count > maxLength else { return self }
        return String(prefix(maxLength - 3)) + "..."
    }

    func collapsingWhitespace() -> String {
        components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }
}
